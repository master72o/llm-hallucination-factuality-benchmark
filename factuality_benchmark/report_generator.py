"""
Report Generator for LLM Hallucination & Factuality Benchmark.
"""

import os
import json
import pandas as pd
from typing import List, Dict, Any
from factuality_benchmark.schema import FactualityResult


class ReportGenerator:
    """Generates Markdown research reports and JSON/CSV data exports."""

    @staticmethod
    def generate_markdown_report(metrics: Dict[str, Any], output_path: str) -> str:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        total = metrics.get("total_items", 0)
        passed = metrics.get("passed_count", 0)
        failed = metrics.get("failed_count", 0)
        pass_rate = metrics.get("pass_rate", 0.0) * 100
        prec = metrics.get("macro_precision", 0.0)
        rec = metrics.get("macro_recall", 0.0)
        f1 = metrics.get("macro_f1", 0.0)

        tax_rows = []
        for t_type, stats in metrics.get("taxonomy_distribution", {}).items():
            tax_rows.append(f"| `{t_type}` | {stats['count']} | {stats['percentage']:.1f}% |")
        tax_table = "\n".join(tax_rows) if tax_rows else "| None | 0 | 0.0% |"

        content = f"""# LLM Hallucination & Factuality Benchmark Report

## Executive Summary

- **Total Evaluated Prompt Items**: `{total}`
- **Passed Quality Gate (Precision >= 0.80 & No Critical Hallucination)**: `{passed}` (`{pass_rate:.1f}%`)
- **Failed Quality Gate**: `{failed}` (`{100 - pass_rate:.1f}%`)
- **Macro Factuality Precision**: `{prec:.4f}`
- **Macro Hallucination Recall**: `{rec:.4f}`
- **Macro Factuality F1 Score**: `{f1:.4f}`

---

## Factuality Performance Metrics

| Metric | Measured Value | Quality Target | Status |
| :--- | :--- | :--- | :--- |
| **Factuality Precision** | `{prec:.4f}` | `0.8000` | {"PASSED" if prec >= 0.80 else "NEEDS IMPROVEMENT"} |
| **Hallucination Recall** | `{rec:.4f}` | `0.8000` | {"PASSED" if rec >= 0.80 else "NEEDS IMPROVEMENT"} |
| **Factuality F1 Score** | `{f1:.4f}` | `0.8000` | {"PASSED" if f1 >= 0.80 else "NEEDS IMPROVEMENT"} |
| **Overall Pass Rate** | `{pass_rate:.1f}%` | `75.0%` | {"PASSED" if pass_rate >= 75.0 else "NEEDS IMPROVEMENT"} |

---

## Hallucination Taxonomy Frequency Breakdown

| Hallucination Error Category | Count | Percentage |
| :--- | :--- | :--- |
{tax_table}

---

## Key Diagnostic Findings

1. **Incorrect Dates & Numbers**: Numerical and chronological claims accounted for the highest rate of hallucination errors in model completions.
2. **Fabricated Entities**: Candidate completions frequently generated non-existent URL parameters or fake organization names when ungrounded.
3. **Evidence Grounding Impact**: Strict sentence-level claim decomposition identified unsupported assertions that traditional BLEU/ROUGE metrics overlooked.

---

## Visualizations

- Factuality & Grounding Metrics: `reports/figures/factuality_metrics.png`
- Hallucination Taxonomy Breakdown: `reports/figures/hallucination_taxonomy_breakdown.png`

---
*Report auto-generated by LLM Hallucination & Factuality Benchmark v1.0.0*
"""

        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        return content

    @staticmethod
    def export_results(results: List[FactualityResult], output_dir: str):
        os.makedirs(output_dir, exist_ok=True)

        json_path = os.path.join(output_dir, "factuality_results.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump([r.to_dict() for r in results], f, indent=2)

        csv_rows = []
        for r in results:
            csv_rows.append({
                "item_id": r.item_id,
                "precision": r.precision,
                "recall": r.recall,
                "f1_score": r.f1_score,
                "passed": r.passed,
                "primary_hallucination": r.primary_hallucination_type.value if hasattr(r.primary_hallucination_type, "value") else r.primary_hallucination_type,
                "prompt": r.prompt,
                "response": r.response,
            })

        df = pd.DataFrame(csv_rows)
        csv_path = os.path.join(output_dir, "factuality_results.csv")
        df.to_csv(csv_path, index=False)
